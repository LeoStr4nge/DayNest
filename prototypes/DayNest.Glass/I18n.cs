    public static string T(string text)
    {
        if (Language == "zh-CN") return text;
        var translations = Language == "ja-JP" ? Japanese : English;
        if (translations.TryGetValue(text, out var translation)) return translation;
        var patterns = Language == "ja-JP" ? JapanesePatterns : new (string Pattern, string Replacement)[]
        {
            (@"^玻璃浓度 (.+)%$", "Glass intensity $1%"),
            (@"^还有 (\d+) 天$", "$1 days left"), (@"^已过 (\d+) 天$", "$1 days ago"),
            (@"^查看日程：(.+)$", "View event: $1"),
            (@"^固定倒计时：(.+)，(.+)$", "Pinned countdown: $1, $2"),
            (@"^(\d{4}-\d\d-\d\d) · (\d+) 项日程$", "$1 · $2 events"),
            (@"^确定删除“(.+)”？\n\n此操作会从日历服务中删除日程，其他设备也会同步删除。$", "Delete “$1”?\n\nThis removes the event from the calendar service and other devices."),
            (@"^已同步 · (.+)$", "Synced · $1"),
            (@"^日历服务返回未授权的服务器地址：(.+)；请检查服务配置和额外可信地址$", "Calendar service returned an unauthorized server URL: $1. Check the service and trusted origins."),
            (@"^日历服务返回 HTTP (\d+)$", "Calendar service returned HTTP $1"),
            (@"^日历服务写入失败：HTTP (\d+)$", "Calendar service write failed: HTTP $1"),
            (@"^日历服务删除失败：HTTP (\d+)$", "Calendar service delete failed: HTTP $1"),
            (@"^无法解析重复日程规则：(.+)$", "Could not parse recurrence rule: $1"),
        };
        foreach (var (pattern, replacement) in patterns)
            if (Regex.IsMatch(text, pattern, RegexOptions.Singleline)) return Regex.Replace(text, pattern, replacement, RegexOptions.Singleline);
        if (text.StartsWith("部分固定项暂未能更新，已保留上次数据。 ", StringComparison.Ordinal))
            return T("部分固定项暂未能更新，已保留上次数据。") + " " +
                T(text["部分固定项暂未能更新，已保留上次数据。 ".Length..]);
        return text;
    }

    public static string FallbackName(string text) => text is "无标题" or "未命名日历" ? T(text) : text;
